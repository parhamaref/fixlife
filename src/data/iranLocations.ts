/**
 * تبدیل اعداد فارسی و عربی به انگلیسی برای اعتبارسنجی دقیق فرم‌ها
 */
export function normalizeDigits(value: string): string {
  if (!value) return '';
  return value
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 1776))
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 1632))
    .replace(/[^0-9]/g, '');
}

/**
 * تبدیل اعداد انگلیسی به ارقام فارسی برای نمایش زیبا در رابط کاربری
 */
export function toPersianDigits(value: number | string): string {
  const str = String(value);
  return str.replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]);
}

/**
 * فرمت مبلغ به تومان با جداکننده هزارگان فارسی
 */
export function formatToman(amountToman: number, includeUnit = true): string {
  const rounded = Math.round(amountToman);
  const formatted = rounded.toLocaleString('fa-IR');
  return includeUnit ? `${formatted} تومان` : formatted;
}

/**
 * اعتبارسنجی شماره موبایل ایران (دقیقاً ۱۱ رقم و شروع با 09)
 */
export function isValidIranMobile(phone: string): boolean {
  const clean = normalizeDigits(phone);
  return /^09\d{9}$/.test(clean);
}

/**
 * اعتبارسنجی کد پستی ۱۰ رقمی ایران (دقیقاً ۱۰ رقم عددی)
 */
export function isValidIranPostalCode(postalCode: string): boolean {
  const clean = normalizeDigits(postalCode);
  return /^\d{10}$/.test(clean);
}

/**
 * بررسی معتبر بودن استان و شهر انتخاب‌شده در لیست شهرهای ایران
 */
export function isValidIranLocation(provinceName: string, cityName: string): boolean {
  const prov = IRAN_PROVINCES.find((p) => p.name === provinceName.trim());
  if (!prov) return false;
  return prov.cities.includes(cityName.trim());
}
